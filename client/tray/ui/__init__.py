"""Интерфейс TrayAgent на Qt (PySide6) — тёмное «жидкое стекло» (спека 1.22).

Прежняя отрисовка (`tkinter`) давала «деревянные» окна: прямоугольные кнопки,
системные шрифты, без полупрозрачности и скруглений. Заказчик просил вид
«как в iOS 27 / macOS»: тёмные полупрозрачные панели со размытием фона.

Разложение по модулям:

* `glass.py` — работа с DWM: acrylic-подложка (размытие фона) и скругления углов.
  Никакого состояния: чистые функции и миксин, который применяет их к окну
  после создания HWND;
* `theme.py` — палитра, размеры и QSS: цвета важности, категорий, радиусы,
  типографика. Всё оформление собрано в одном месте;
* `widgets.py` — общие элементы: «стеклянная» панель, кнопка-плашка, плашка
  категории и важности;
* `toast.py` — всплывающее уведомление в правом верхнем углу (как в Telegram);
* `reader.py` — окно-читалка: полное тело, перетаскивание и изменение размера;
* `panel.py` — меню со списком уведомлений, вкладками и переключателем группировки;
* `tray_windows.py` — адаптер `TrayWindows`: тот же интерфейс, что у tkinter-версии,
  поэтому `TrayAgent` не меняется.

Важно: `tkinter` здесь не используется вовсе, а `pystray` заменён на
`QSystemTrayIcon` — один стек, один цикл событий.
"""
